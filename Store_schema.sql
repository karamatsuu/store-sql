/*=====================================================================
  Store — retail sales model (Microsoft SQL Server / T-SQL)

  Creates the Store database with REGION, EMPLOYEE and STORE tables.

  Requirements covered:
    - SEQUENCE dbo.EMP_CODE_SEQ supplies EMPLOYEE.EMP_CODE (NEXT VALUE FOR).
    - EMPLOYEE.Store_code DEFAULT 3.
    - STORE.store_ytd_sales CHECK (> 0) — only positive values allowed.
    - Primary keys + foreign keys per the reference tables.

  Note on the CIRCULAR relationship:
    STORE.EMP_CODE references EMPLOYEE (the store manager), and
    EMPLOYEE.STORE_CODE references STORE (where the employee works).
    To load data without a chicken-and-egg deadlock, EMPLOYEE is created
    first WITHOUT its FK to STORE; the FK is added at the end, after both
    tables are populated.

  The script is RE-RUNNABLE: it drops objects (breaking the FK cycle first)
  before recreating them, so repeated runs finish without errors.
=====================================================================*/

-------------------------------------------------------------------------------
-- 1. Database
-------------------------------------------------------------------------------
USE master;
GO

IF DB_ID('Store') IS NULL
    CREATE DATABASE Store;
GO

USE Store;
GO

-------------------------------------------------------------------------------
-- 2. Clean up for re-runnability (break the circular FK first)
-------------------------------------------------------------------------------
IF OBJECT_ID('FK_EMPLOYEE_STORE', 'F') IS NOT NULL
    ALTER TABLE EMPLOYEE DROP CONSTRAINT FK_EMPLOYEE_STORE;
GO

DROP TABLE IF EXISTS STORE;
DROP TABLE IF EXISTS EMPLOYEE;
DROP TABLE IF EXISTS REGION;
DROP SEQUENCE IF EXISTS dbo.EMP_CODE_SEQ;
GO

-------------------------------------------------------------------------------
-- 3. Sequence for EMP_CODE
-------------------------------------------------------------------------------
CREATE SEQUENCE dbo.EMP_CODE_SEQ AS INT START WITH 1 INCREMENT BY 1;
GO

-------------------------------------------------------------------------------
-- 4. Tables
-------------------------------------------------------------------------------
CREATE TABLE REGION (
    REGION_CODE     INT          NOT NULL,
    REGION_DESCRIPT VARCHAR(50)  NOT NULL,
    CONSTRAINT PK_REGION PRIMARY KEY (REGION_CODE)
);
GO

-- EMPLOYEE is created WITHOUT the FK to STORE (added in step 6).
-- EMP_CODE defaults to the sequence; Store_code defaults to 3.
CREATE TABLE EMPLOYEE (
    EMP_CODE    INT         NOT NULL
        CONSTRAINT DF_EMPLOYEE_EmpCode DEFAULT (NEXT VALUE FOR dbo.EMP_CODE_SEQ),
    EMP_TITLE   VARCHAR(4)  NULL,
    EMP_LNAME   VARCHAR(50) NOT NULL,
    EMP_FNAME   VARCHAR(50) NOT NULL,
    EMP_INITIAL CHAR(1)     NULL,
    EMP_DOB     DATE        NULL,
    STORE_CODE  INT         NOT NULL
        CONSTRAINT DF_EMPLOYEE_StoreCode DEFAULT (3),
    CONSTRAINT PK_EMPLOYEE PRIMARY KEY (EMP_CODE)
);
GO

CREATE TABLE STORE (
    STORE_CODE      INT            NOT NULL,
    STORE_NAME      VARCHAR(50)    NOT NULL,
    STORE_YTD_SALES NUMERIC(12, 2) NOT NULL
        CONSTRAINT CK_STORE_YTD_Sales CHECK (STORE_YTD_SALES > 0),
    REGION_CODE     INT            NOT NULL,
    EMP_CODE        INT            NOT NULL,   -- store manager
    CONSTRAINT PK_STORE PRIMARY KEY (STORE_CODE),
    CONSTRAINT FK_STORE_REGION
        FOREIGN KEY (REGION_CODE) REFERENCES REGION (REGION_CODE),
    CONSTRAINT FK_STORE_EMPLOYEE
        FOREIGN KEY (EMP_CODE) REFERENCES EMPLOYEE (EMP_CODE)
);
GO

